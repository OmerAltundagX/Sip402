#!/usr/bin/env bash
# Exports the Sip402 ABI as a typed TypeScript module shared by the server and web app.
set -euo pipefail
cd "$(dirname "$0")/.."
forge build --silent
abi=$(forge inspect src/Sip402.sol:Sip402 abi --json)
printf '// Generated by script/export-abi.sh. Do not edit.\nexport const sip402Abi = %s as const;\n' "$abi" > shared/sip402Abi.ts
echo "ABI exported to shared/sip402Abi.ts"
